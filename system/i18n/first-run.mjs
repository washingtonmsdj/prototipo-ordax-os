const CATALOGS = Object.freeze({
  "en-US": EN,
  "pt-BR": Object.freeze({ ...EN, ...PT }),
  "es-419": Object.freeze({ ...EN, ...ES }),
  "fr-FR": Object.freeze({ ...EN, ...FR }),
});

export function firstRunText(locale, key, variables = {}) {
  const catalog = CATALOGS[locale] ?? EN;
  let value = catalog[key] ?? EN[key];
  if (typeof value !== "string") throw new TypeError(`Unknown first-run i18n key: ${String(key)}`);
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function firstRunStepLabels(locale) {
  return Object.freeze([
    firstRunText(locale, "stepWelcome"),
    firstRunText(locale, "stepRegional"),
    firstRunText(locale, "stepNetwork"),
    firstRunText(locale, "stepAccount"),
    firstRunText(locale, "stepPrivacy"),
    firstRunText(locale, "stepReady"),
  ]);
}
